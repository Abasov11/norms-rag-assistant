"""
Иллюстративный фрагмент из RAG-ассистента по нормативной базе (портфолио-кейс, не рабочая сборка).

Парсер извлекает структуру PDF-норм (раздел -> пункт) и по умолчанию считал всё после
первого слова «ПРИЛОЖЕНИЕ» на странице служебным хвостом и отрезал его. Для большинства
СП/СН это верно (приложения — формы актов). Для части документов (например, у стандартов
серии EN, где нормативные требования продолжаются в приложениях) это ломает систему: у
двух таких документов доля текста, попавшая в структуру, была 0.21–0.45 — то есть 55–80%
нормативного текста ответам ассистента было физически недоступно.

Индикатор для приёмки/карантина: coverage = доля текста документа, попавшая хоть в один
узел структуры. Ниже показан упрощённый расчёт этой метрики и эвристика «это оглавление,
а не начало приложения» — без неё строка вида «Приложение Ж зоны ... 74» из содержания
ошибочно распознаётся как заголовок настоящего приложения.
"""
from __future__ import annotations

import re

RX_APPENDIX_HEADING = re.compile(r"^\s*ПРИЛОЖЕНИЕ\s+([А-ЯЁA-Za-z]|\d{1,2})\b", re.I)
RX_TOC_LEADER = re.compile(r"\.{3,}|…")          # точки-лидеры оглавления
RX_TOC_PAGE_TAIL = re.compile(r"\s\d{1,3}\s*$")   # номер страницы в хвосте строки
MAX_HEADING_TAIL_LEN = 60


def appendix_heading(line: str) -> str | None:
    """Буква приложения, если строка — настоящий заголовок, а не строка оглавления
    или мимоходное упоминание. Судим по остатку строки после номера: у заголовка он
    пуст или короткая пометка «(обязательное)», у строки оглавления — точки-лидеры
    и номер страницы в хвосте."""
    match = RX_APPENDIX_HEADING.match(line)
    if not match:
        return None
    tail = line[match.end():].strip()
    if RX_TOC_LEADER.search(tail) or RX_TOC_PAGE_TAIL.search(tail) or len(tail) > MAX_HEADING_TAIL_LEN:
        return None
    return match.group(1).upper()


def coverage(document_chars: int, structured_chars: int) -> float:
    """Доля текста документа, вошедшая в структуру (узлы разделов/пунктов/приложений).
    Знаменатель — весь документ, а не только «основная» часть без приложений: иначе
    метрика не видит собственную причину потери текста."""
    return round(structured_chars / document_chars, 2) if document_chars else 0.0


# Порог приёмки в структуру (карантин ниже порога — документ ждёт доработки парсера,
# а не заливается с дырой в нормативном тексте):
ACCEPT_COVERAGE = 0.75
QUARANTINE_COVERAGE = 0.60
